// ═══════════════════════════════════════════════════════════════════════════════
// DEBUG — ręczne sprawdzenie nowych wiadomości przez delta query
// POST /api/crm/outlook/debug/process
// ═══════════════════════════════════════════════════════════════════════════════

async function debugProcessHandler(req, res) {
  try {
    const { rows } = await pool.query(
      "SELECT email, delta_link FROM tenant_outlook_tokens WHERE tenant_id = $1",
      [req.tenantId],
    );
    if (!rows.length) return res.status(404).json({ error: "Brak podłączonej skrzynki firmowej Outlook" });

    const { email, delta_link } = rows[0];

    const { deltaLink, newMessages } = await outlookService.getTenantNewMessages(req.tenantId);

    const note = !delta_link
      ? "delta_link był pusty — ustawiono bazowy punkt. Wyślij do siebie email i kliknij ponownie."
      : null;

    res.json({
      ok: true,
      email,
      note,
      deltaLink_initialized: !delta_link,
      newMessages_found: newMessages.length,
      newMessages: newMessages.slice(0, 10).map(m => ({
        id:             m.id,
        subject:        m.subject,
        from:           m.from?.emailAddress?.address,
        conversationId: m.conversationId,
        receivedAt:     m.receivedDateTime,
      })),
    });
  } catch (err) {
    console.error("[Outlook] debug/process error:", err.message);
    const status = err.code === "PROVIDER_NOT_CONFIGURED" ? (err.status || 400) : 500;
    res.status(status).json({ error: err.message, ...(err.code ? { code: err.code } : {}) });
  }
}
router.post("/debug/process", requireAuth, crmAuth, outlookGate, debugProcessHandler);

