// Company mailbox connect/status/disconnect are super-admin-only actions,
// performed from Tenant → Email in the admin panel — never from a lead or
// partner view. tenantId is an explicit query param because the calling
// super admin manages an arbitrary tenant, not necessarily their own.
router.get("/oauth/url", requireAuth, requireSuperAdmin, async (req, res, next) => {
  try {
    const { tenantId } = req.query;
    if (!tenantId) return res.status(400).json({ error: "tenantId jest wymagany" });
    const gate = await resolveProviderGate(tenantId, "outlook");
    if (!gate.ok) {
      return res.status(gate.active ? 403 : 400).json({
        error: gate.active
          ? `Ta organizacja korzysta z innego dostawcy poczty (${gate.active}).`
          : "Outlook nie jest aktywnym providerem dla tego tenanta.",
        code: "PROVIDER_NOT_ACTIVE",
      });
    }
    const url = await outlookService.getTenantAuthUrl(tenantId, req.user.id);
    res.json({ url });
  } catch (err) { next(err); }
});

// No requireAuth — Microsoft redirects the browser without Authorization header.
// tenantId is encoded in the HMAC-signed state parameter generated by /oauth/url.
router.get("/oauth/callback", async (req, res) => {
  try {
    const { code, error, state } = req.query;
    if (error) return res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=${encodeURIComponent(error)}`);
    if (!code)  return res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=no_code`);
    if (!state) return res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=missing_state`);

    const parsed = outlookService.parseTenantOAuthState(state);
    if (!parsed) {
      return res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=invalid_state`);
    }
    const { tenantId, initiatingUserId } = parsed;

    const gate = await resolveProviderGate(tenantId, "outlook");
    if (!gate.ok) {
      return res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=provider_not_active`);
    }

    await outlookService.exchangeTenantCodeAndSave(code, tenantId, initiatingUserId);

    res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=connected`);
  } catch (err) {
    console.error("[Outlook] OAuth callback error:", err.message);
    res.redirect(`${config.frontendUrl}/crm/outlook/callback?status=error&reason=callback_failed`);
  }
});

async function statusHandler(req, res) {
  try {
    const { tenantId } = req.query;
    if (!tenantId) return res.status(400).json({ error: "tenantId jest wymagany" });
    const status = await outlookService.getTenantMailboxStatus(tenantId);
    res.json(status);
  } catch (err) {
    res.status(500).json({ error: "Błąd serwera" });
  }
}
router.get("/status", requireAuth, requireSuperAdmin, statusHandler);

async function disconnectHandler(req, res) {
  try {
    const { tenantId } = req.query;
    if (!tenantId) return res.status(400).json({ error: "tenantId jest wymagany" });
    await outlookService.disconnectTenantMailbox(tenantId);
    res.json({ ok: true });
  } catch (err) {
    res.status(500).json({ error: "Błąd serwera" });
  }
}
router.delete("/oauth/disconnect", requireAuth, requireSuperAdmin, disconnectHandler);

